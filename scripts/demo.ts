import {mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createBaseline} from '../src/demo/interpreter.ts';
import {connectPorts,createNode,deleteRelation,ensureGraph} from '../src/core/graph.ts';
import {analyzeChange,analyzeDependencies} from '../src/core/impact.ts';
import {parseModel,serializeModel} from '../src/core/persistence.ts';
mkdirSync('evidence',{recursive:true});
const actor='Demo incremento 1 · azioni simulate';
const before=ensureGraph(createBaseline());
const withSite=createNode(before,{id:'SITE',kind:'entity',label:'Sede',description:'Concetto aggiunto dall’editor di progetto; nessun comportamento medico implicito.'},actor,{x:720,y:430});
const after=connectPorts(withSite,'DOC','out:works-at','SITE','in:works-at',actor);
const change=after.graph!.changes.at(-1)!;
const report=analyzeChange(after,change);
for(const id of ['AGENDA','BOOK','EMAIL'])assert.ok(report.impacts.some(i=>i.target===id));
const dependency=after.relations.find(r=>r.type==='depends-on'&&r.from==='BOOK'&&r.to==='AGENDA')!;
const cut=deleteRelation(after,dependency.id,actor),afterCut=analyzeDependencies(cut,['SITE']);
assert.ok(!afterCut.impacts.some(i=>i.target==='BOOK'||i.target==='EMAIL'));
assert.equal(serializeModel(parseModel(serializeModel(after))),serializeModel(after));
assert.equal(after.multiSite,before.multiSite);
const proof={generatedAt:new Date().toISOString(),experiment:'Blueprint Incremento 1',notice:'Creazione e collegamento effettuati tramite gli stessi comandi del grafo. Nessuna analisi AI, nessun nuovo comportamento medico.',before,withSite,after,change,report,negativeControl:{operation:'Rimozione della dipendenza Prenotazione → Agenda',model:cut,report:afterCut},persistenceRoundTrip:'pass'};
writeFileSync('evidence/increment-1-demo.json',JSON.stringify(proof,null,2));
writeFileSync('evidence/centro-medico-grafo.json',serializeModel(after));
console.log('Creato Sede; collegato Medico —works-at→ Sede.');
console.log('Modello: '+before.elements.length+' → '+after.elements.length+' nodi; '+before.relations.length+' → '+after.relations.length+' connessioni.');
for(const impact of report.impacts)console.log(impact.classification.toUpperCase()+' '+impact.path.map(id=>after.elements.find(e=>e.id===id)?.label??id).join(' → '));
console.log('Controllo negativo: rimossa Prenotazione → Agenda; Prenotazione e Notifica non più raggiunte da Sede.');
console.log('Persistenza: serializzazione e ripristino identici. Nessuna funzione medica attivata.');
console.log('Prova: evidence/increment-1-demo.json · modello importabile: evidence/centro-medico-grafo.json');
